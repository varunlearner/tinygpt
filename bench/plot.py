"""Generate every figure + a markdown summary from the raw JSON files in results/.

    python -m bench.plot --results results          # -> results/plots/*.png and results/SUMMARY.md

Figures are never hand-made: they are regenerated from the committed JSON.
"""
from __future__ import annotations

import argparse
import glob
import json
import os
from collections import defaultdict

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt  # noqa: E402


def _title(res: dict) -> str:
    e = res["env"]
    return f"{e['device_name']} ({e['device']}, {e['dtype']})"


def plot_e1(path: str, outdir: str) -> str:
    res = json.load(open(path))
    rows = res["rows"]
    xs = [r["new_tokens"] for r in rows]
    fig, ax = plt.subplots(1, 2, figsize=(11, 4))
    if any("naive" in r for r in rows):
        ax[0].plot([r["new_tokens"] for r in rows if "naive" in r], [r["naive"]["tokens_per_s"] for r in rows if "naive" in r],
                   "o-", label="naive (recompute)")
    ax[0].plot(xs, [r["cached"]["tokens_per_s"] for r in rows], "s-", label="KV cache")
    ax[0].set_xlabel("generated tokens"); ax[0].set_ylabel("decode tokens / s"); ax[0].set_xscale("log", base=2)
    ax[0].legend(); ax[0].grid(alpha=0.3); ax[0].set_title("E1: throughput vs generation length")
    sp = [(r["new_tokens"], r["speedup"]) for r in rows if "speedup" in r]
    if sp:
        ax[1].plot(*zip(*sp), "o-", color="C2")
        ax[1].axhline(1.0, ls="--", color="gray")
    ax[1].set_xlabel("generated tokens"); ax[1].set_ylabel("speedup (cached / naive)"); ax[1].set_xscale("log", base=2)
    ax[1].grid(alpha=0.3); ax[1].set_title("KV cache speedup")
    fig.suptitle(_title(res)); fig.tight_layout()
    dst = os.path.join(outdir, os.path.basename(path).replace(".json", ".png"))
    fig.savefig(dst, dpi=140); plt.close(fig)
    return dst


def plot_e2(path: str, outdir: str) -> str:
    res = json.load(open(path))
    rows = res["rows"]
    fig, ax = plt.subplots(figsize=(6, 4))
    ax.plot([r["batch"] for r in rows], [r["tokens_per_s"] for r in rows], "o-")
    ax.set_xscale("log", base=2); ax.set_xlabel("batch size"); ax.set_ylabel("total decode tokens / s")
    ax.grid(alpha=0.3); ax.set_title(f"E2: batch scaling\n{_title(res)}")
    fig.tight_layout()
    dst = os.path.join(outdir, os.path.basename(path).replace(".json", ".png"))
    fig.savefig(dst, dpi=140); plt.close(fig)
    return dst


def plot_e3(path: str, outdir: str) -> str:
    res = json.load(open(path))
    spec = [r for r in res["rows"] if r.get("kind") == "speculative"]
    temps = sorted({r["temperature"] for r in spec})
    fig, ax = plt.subplots(2, len(temps), figsize=(4.6 * len(temps), 7), squeeze=False)
    for j, t in enumerate(temps):
        by_draft = defaultdict(list)
        for r in spec:
            if r["temperature"] == t:
                by_draft[r["draft"]].append(r)
        for name, rs in by_draft.items():
            rs.sort(key=lambda r: r["k"])
            ax[0][j].plot([r["k"] for r in rs], [r["speedup_median"] for r in rs], "o-", label=name)
            ax[1][j].plot([r["k"] for r in rs], [r["acceptance_rate"] for r in rs], "o-", label=name)
        ax[0][j].axhline(1.0, ls="--", color="gray")
        ax[0][j].set_title(f"temperature {t}"); ax[0][j].set_ylabel("speedup vs cached"); ax[0][j].grid(alpha=0.3)
        ax[1][j].set_xlabel("k (draft tokens / round)"); ax[1][j].set_ylabel("acceptance rate"); ax[1][j].set_ylim(0, 1.02)
        ax[1][j].grid(alpha=0.3)
        if j == 0:
            ax[0][j].legend(fontsize=8)
    fig.suptitle("E3: speculative decoding - " + _title(res)); fig.tight_layout()
    dst = os.path.join(outdir, os.path.basename(path).replace(".json", ".png"))
    fig.savefig(dst, dpi=140); plt.close(fig)
    return dst


def plot_e4(path: str, outdir: str) -> str:
    res = json.load(open(path))
    rows = res["rows"]
    fig, ax = plt.subplots(figsize=(5, 5))
    ax.scatter([r["predicted_speedup"] for r in rows], [r["measured_speedup"] for r in rows], c=[r["k"] for r in rows])
    lim = max(max(r["predicted_speedup"] for r in rows), max(r["measured_speedup"] for r in rows)) * 1.1
    ax.plot([0, lim], [0, lim], "--", color="gray"); ax.set_xlim(0, lim); ax.set_ylim(0, lim)
    ax.set_xlabel("theory  (1-a^(k+1)) / ((1-a)(kc+1))"); ax.set_ylabel("measured speedup")
    ax.set_title("E4: theory vs measured\n" + _title(res)); ax.grid(alpha=0.3)
    fig.tight_layout()
    dst = os.path.join(outdir, os.path.basename(path).replace(".json", ".png"))
    fig.savefig(dst, dpi=140); plt.close(fig)
    return dst


def summary(results_dir: str) -> str:
    lines = ["# Results summary (auto-generated by `python -m bench.plot`)\n"]
    for path in sorted(glob.glob(os.path.join(results_dir, "E1_*.json"))):
        res = json.load(open(path))
        lines += [f"## E1 - {_title(res)} - `{os.path.basename(path)}`\n", "| new tokens | naive tok/s | cached tok/s | speedup |",
                  "|---|---|---|---|"]
        for r in res["rows"]:
            n = f"{r['naive']['tokens_per_s']:.1f}" if "naive" in r else "-"
            s = f"{r['speedup']:.2f}x" if "speedup" in r else "-"
            lines.append(f"| {r['new_tokens']} | {n} | {r['cached']['tokens_per_s']:.1f} | {s} |")
        lines.append("")
    for path in sorted(glob.glob(os.path.join(results_dir, "E3_*.json"))):
        res = json.load(open(path))
        spec = [r for r in res["rows"] if r.get("kind") == "speculative"]
        lines += [f"## E3 - {_title(res)} - `{os.path.basename(path)}`\n",
                  "| temp | draft | best k | alpha | tokens/round | tok/s | speedup |", "|---|---|---|---|---|---|---|"]
        for t in sorted({r["temperature"] for r in spec}):
            for d in sorted({r["draft"] for r in spec}):
                cand = [r for r in spec if r["temperature"] == t and r["draft"] == d]
                b = max(cand, key=lambda r: r["speedup_median"])
                lines.append(f"| {t} | {d} | {b['k']} | {b['acceptance_rate']:.2f} | {b['mean_tokens_per_round']:.2f} | "
                             f"{b['tokens_per_s']:.1f} | {b['speedup_median']:.2f}x |")
        lines.append("")
    return "\n".join(lines)


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--results", default="results")
    args = ap.parse_args()
    outdir = os.path.join(args.results, "plots")
    os.makedirs(outdir, exist_ok=True)
    made = []
    for path in sorted(glob.glob(os.path.join(args.results, "E1_*.json"))):
        made.append(plot_e1(path, outdir))
    for path in sorted(glob.glob(os.path.join(args.results, "E2_*.json"))):
        made.append(plot_e2(path, outdir))
    for path in sorted(glob.glob(os.path.join(args.results, "E3_*.json"))):
        made.append(plot_e3(path, outdir))
    for path in sorted(glob.glob(os.path.join(args.results, "analysis_E4_*.json"))):
        if json.load(open(path))["rows"]:
            made.append(plot_e4(path, outdir))
    with open(os.path.join(args.results, "SUMMARY.md"), "w") as f:
        f.write(summary(args.results))
    print("wrote:\n  " + "\n  ".join(made + [os.path.join(args.results, "SUMMARY.md")]))


if __name__ == "__main__":
    main()
